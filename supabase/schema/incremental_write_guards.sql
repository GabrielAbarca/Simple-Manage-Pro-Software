-- ═══════════════════════════════════════════════════════════════
--  Write middleware, part 1: guards + audit log
--  Apply to every SCHOOL project before any incremental_write_*.sql file.
-- ═══════════════════════════════════════════════════════════════
--
-- WHY THIS EXISTS
-- The browser used to write straight to tables, so RLS was the only check,
-- and the teacher write policies never bound student_id. Writes now go
-- through SECURITY DEFINER functions (incremental_write_*.sql) that call
-- these guards first. Once incremental_revoke_direct_writes.sql removes
-- direct DML from `authenticated`, those functions are the only way in.
--
-- The guards raise generic messages on purpose: the client maps SQLSTATE to
-- its own i18n text (src/js/dbErrors.js), and "not permitted" must not tell a
-- caller whether a row exists.
--   42501  caller may not touch this row
--   22023  the payload itself is malformed
--
-- Every helper here is callable only from other definer functions: EXECUTE
-- is revoked from anon/authenticated, and a definer function checks EXECUTE
-- against its owner, not the caller.
--
-- Idempotent: safe to re-run.

-- ── Audit log ──────────────────────────────────────────────────
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor uuid default auth.uid(),
  action text not null,
  entity text not null,
  entity_id integer,
  detail jsonb,
  created_at timestamp with time zone not null default now()
);

create index if not exists idx_audit_log_entity
  on public.audit_log (entity, entity_id);

alter table public.audit_log enable row level security;
revoke all on public.audit_log from anon, authenticated, public;
grant select on public.audit_log to authenticated;

drop policy if exists "Admins read the audit log" on public.audit_log;
create policy "Admins read the audit log" on public.audit_log
  for select to authenticated
  using (public.is_admin());

create or replace function public.log_write(
  p_action text, p_entity text, p_entity_id integer, p_detail jsonb)
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
  insert into public.audit_log (action, entity, entity_id, detail)
  values (p_action, p_entity, p_entity_id, p_detail);
$$;

-- ── Demo guard ─────────────────────────────────────────────────
-- A definer function runs as the table owner, which skips the demo_deny_*
-- restrictive policies. Refusing here keeps the demo read-only even if
-- demo_lockdown.sql was not re-run after these functions were added.
create or replace function public.assert_not_demo()
returns void
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if exists (select 1 from pg_policies
              where schemaname = 'public' and policyname = 'demo_deny_insert') then
    raise exception 'not permitted' using errcode = '42501';
  end if;
end;
$$;

-- ── Ownership guards ───────────────────────────────────────────
-- Returns the CST's class, so callers derive class_id from the server's
-- record instead of trusting one sent by the browser.
create or replace function public.assert_teacher_cst(p_cst integer)
returns integer
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_class integer;
begin
  select cst.class_id into v_class
    from public.class_subject_teachers cst
   where cst.id = p_cst
     and (cst.teacher_id = public.teacher_id() or public.is_admin());
  if v_class is null then
    raise exception 'not permitted' using errcode = '42501';
  end if;
  return v_class;
end;
$$;

create or replace function public.assert_students_in_class(
  p_class integer, p_ids integer[])
returns void
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if exists (
    select unnest(p_ids)
    except
    select s.id from public.students s where s.class_id = p_class
  ) then
    raise exception 'not permitted' using errcode = '42501';
  end if;
end;
$$;

create or replace function public.assert_date_in_cst_year(
  p_cst integer, p_date date)
returns void
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if p_date is null or not exists (
    select 1
      from public.class_subject_teachers cst
      join public.school_years y on y.id = cst.school_year_id
     where cst.id = p_cst
       and p_date between y.start_date and y.end_date
  ) then
    raise exception 'date outside the school year' using errcode = '22023';
  end if;
end;
$$;

-- ── Grants ─────────────────────────────────────────────────────
-- Supabase's default privileges grant EXECUTE on new functions to anon and
-- authenticated, so each one is revoked explicitly.
revoke execute on function public.log_write(text, text, integer, jsonb)
  from anon, authenticated, public;
revoke execute on function public.assert_not_demo()
  from anon, authenticated, public;
revoke execute on function public.assert_teacher_cst(integer)
  from anon, authenticated, public;
revoke execute on function public.assert_students_in_class(integer, integer[])
  from anon, authenticated, public;
revoke execute on function public.assert_date_in_cst_year(integer, date)
  from anon, authenticated, public;
